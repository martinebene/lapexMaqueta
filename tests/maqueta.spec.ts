
import { test, expect } from "@playwright/test"
test("Crear sesión exige datos y abre módulos seleccionados",async({page})=>{
await page.goto("/")
await expect(page.getByRole("heading",{name:"Análisis"})).toBeVisible()
await page.locator("aside").getByRole("button",{name:"Nueva sesión"}).click()
await expect(page.getByRole("heading",{name:"Nueva sesión"})).toBeVisible()
const create=page.getByRole("button",{name:"Crear sesión"})
await expect(create).toBeDisabled()
await page.getByRole("textbox",{name:"Nombre de la sesión"}).fill("Sesión de prueba Nova")
await page.getByRole("radio",{name:"Piloto Demo A"}).check()
await page.getByRole("radio",{name:"Circuito Delta"}).check()
await page.getByRole("radio",{name:"GT-04"}).check()
await page.getByRole("group",{name:"Datos objetivos"}).getByRole("checkbox",{name:"Rodaje · Tanda 02"}).click()
await expect(create).toBeDisabled()
await page.getByRole("group",{name:"Módulos de análisis"}).getByRole("checkbox",{name:"Mejor vuelta"}).click()
await expect(create).toBeEnabled()
await page.getByRole("group",{name:"Datos de referencia"}).getByRole("checkbox",{name:"Rodaje · Referencia 01"}).click()
await create.click()
await expect(page.getByRole("heading",{name:"Sesión de prueba Nova"})).toBeVisible()
await page.getByRole("button",{name:"Módulos de análisis"}).click()
await page.getByRole("button",{name:"Módulos de análisis"}).click()
await page.locator(".group-children").getByRole("button",{name:"Mejor vuelta"}).click()
await expect(page.getByText("Asistente IA contextual")).toBeVisible()
})
test("Biblioteca de datos muestra filtros y lista",async({page})=>{
await page.goto("/")
await page.locator(".modes").getByRole("button",{name:"Datos"}).click()
await expect(page.getByRole("heading",{name:"Biblioteca de datos"})).toBeVisible()
await expect(page.getByRole("table")).toBeVisible()
await page.getByRole("textbox",{name:"Buscar"}).fill("meteorológica")
await expect(page.getByRole("row",{name:/Estación meteorológica/})).toBeVisible()
})

import {test,expect} from "@playwright/test"

test("Importar: ancho completo y filtro de extensiones según el formato seleccionado",async({page})=>{
 await page.goto("/")
 const sidebar=page.locator("[data-sidebar='sidebar']").first()
 await sidebar.getByText("Datos",{exact:true}).click()
 await sidebar.getByText("Importar datos",{exact:true}).click()
 const card=page.locator(".import-card")
 const workspace=page.locator(".workspace")
 await expect(card).toBeVisible()
 const cardBox=await card.boundingBox(),workBox=await workspace.boundingBox()
 expect(cardBox&&workBox).toBeTruthy()
 expect(cardBox!.width).toBeGreaterThan(workBox!.width-120)
 const type=page.getByRole("combobox",{name:"Tipo de archivo"})
 const file=page.locator("#import-file")
 await expect(type).toHaveValue("CSV")
 await expect(file).toHaveAttribute("accept",".csv")
 await expect(page.getByRole("button",{name:"Seleccionar archivo"})).toHaveCount(1)
 await expect(page.locator(".import-file-name")).toHaveText("Ningún archivo seleccionado")
 await type.selectOption("XRK")
 await expect(file).toHaveAttribute("accept",".xrk")
 await file.setInputFiles({name:"vueltas.csv",mimeType:"text/csv",buffer:Buffer.from("muestra")})
 await expect(page.getByRole("alert")).toContainText(".xrk")
 await expect(page.getByRole("button",{name:/Continuar/})).toBeDisabled()
 await file.setInputFiles({name:"vueltas.xrk",mimeType:"application/octet-stream",buffer:Buffer.from("muestra")})
 await expect(page.locator(".import-file-name")).toHaveText("vueltas.xrk")
 await type.selectOption("JSON")
 await expect(file).toHaveAttribute("accept",".json")
 await expect(page.locator(".import-file-name")).toHaveText("Ningún archivo seleccionado")
 await expect(page.getByRole("button",{name:/Continuar/})).toBeDisabled()
 await file.setInputFiles({name:"rodaje.json",mimeType:"application/json",buffer:Buffer.from("{}")})
 await expect(page.getByRole("button",{name:/Continuar/})).toBeEnabled()
})

test("Preferencias: tarjetas, etiquetas y controles con contraste coherente en modo oscuro",async({page})=>{
 await page.goto("/")
 const sidebar=page.locator("[data-sidebar='sidebar']").first()
 await sidebar.getByText("Configuración",{exact:true}).click()
 await sidebar.getByText("Preferencias",{exact:true}).click()
 await page.getByRole("combobox",{name:"Tema"}).selectOption("dark")
 const card=page.locator(".settings-stack > [data-slot=card]").first()
 const label=page.locator(".pref-row span").first()
 const contrast=await label.evaluate(el=>{
  const rgb=(color:string)=>{const v=color.match(/[\\d.]+/g)?.slice(0,3).map(Number)??[0,0,0];const c=v.map(x=>{const s=x/255;return s<=0.04045?s/12.92:((s+0.055)/1.055)**2.4});return c[0]*0.2126+c[1]*0.7152+c[2]*0.0722}
  const fg=rgb(getComputedStyle(el).color),bg=rgb(getComputedStyle(el.closest("[data-slot=card]")!).backgroundColor)
  return (Math.max(fg,bg)+.05)/(Math.min(fg,bg)+.05)
 })
 expect(contrast).toBeGreaterThanOrEqual(4.5)
 const bg=await card.evaluate(el=>getComputedStyle(el).backgroundColor)
 expect(bg).not.toBe("rgb(248, 251, 253)")
 expect(bg).not.toBe("rgb(255, 255, 255)")
 await sidebar.getByText("Mi cuenta",{exact:true}).click()
 const accountCard=page.locator(".account-stack > [data-slot=card]").first()
 await expect(accountCard).toBeVisible()
 expect(await accountCard.evaluate(el=>getComputedStyle(el).backgroundColor)).toBe(bg)
})


test("Circuitos: distancia dinámica con permiso y ordenable",async({page,context})=>{
 await context.grantPermissions(["geolocation"])
 await context.setGeolocation({latitude:-43.25,longitude:-65.31})
 await page.goto("/")
 await sidebar(page).getByRole("button",{name:"Recursos",exact:true}).click()
 await sidebar(page).getByRole("button",{name:"Circuitos"}).click()
 const grid=page.locator(".resources-page .shadcn-grid")
 await expect(grid.getByRole("columnheader",{name:/Distancia/})).toBeVisible()
 await expect(grid.locator("tbody tr").filter({hasText:"Circuito Delta"}).first()).toContainText(/0(?:[,.]0)? km/)
 await expect(grid.locator("tbody tr").filter({hasText:"Circuito Sierra"}).first()).toContainText("No disponible")
 await expect(grid.getByRole("button",{name:/Ordenar por Distancia/}).first()).toBeVisible()
})

test("Recursos: botones iconográficos equivalentes y encabezados alineados",async({page})=>{
 await page.goto("/")
 await sidebar(page).getByRole("button",{name:"Recursos",exact:true}).click()
 await sidebar(page).getByRole("button",{name:"Pilotos"}).click()
 const icons=page.locator(".resources-page .dg-record").first().locator(".dg-icon-button")
 await expect(icons).toHaveCount(3)
 const dimensions=await icons.evaluateAll(els=>els.map(el=>[el.getBoundingClientRect().width,el.getBoundingClientRect().height]))
 expect(new Set(dimensions.map(x=>x.join("x"))).size).toBe(1)
 const headers=page.locator(".resources-page .dg-rows thead th")
 expect(await headers.first().evaluate(el=>getComputedStyle(el).textAlign)).toBe("center")
})

test("Mi cuenta: perfil ampliado y notificaciones configurables en maqueta",async({page})=>{
 await page.goto("/")
 await sidebar(page).getByRole("button",{name:"Configuración"}).click()
 await sidebar(page).getByRole("button",{name:"Mi cuenta"}).click()
 await page.getByRole("button",{name:"Editar perfil"}).click()
 await page.getByRole("textbox",{name:"Nombre real"}).fill("Usuario de prueba")
 await page.getByRole("textbox",{name:"Teléfono"}).fill("+54 000 000")
 await expect(page.getByRole("textbox",{name:"Correo electrónico de registro"})).toBeDisabled()
 await page.getByRole("button",{name:"Guardar perfil"}).click()
 await expect(page.locator("[data-slot=card-title]").filter({hasText:"Notificaciones"})).toBeVisible()
 const promotions=page.getByRole("switch",{name:"Promociones"})
 await expect(promotions).not.toBeChecked()
 await promotions.check()
 await expect(promotions).toBeChecked()
 await expect(page.getByText(/avisos esenciales de seguridad/)).toBeVisible()
})

import {test,expect} from "@playwright/test"
const sidebar=(page:import("@playwright/test").Page)=>page.locator("[data-sidebar='sidebar']").first()

test("Inicio: pantalla inicial sin Volver, incluso al regresar",async({page})=>{
 await page.goto("/")
 await expect(page.getByRole("heading",{name:"Inicio · Lapex"})).toBeVisible()
 await expect(page.locator(".sidebar07-breadcrumb-bar").getByRole("button",{name:"Volver"})).toHaveCount(0)
 await sidebar(page).getByRole("button",{name:"Recursos",exact:true}).click()
 await sidebar(page).getByRole("button",{name:"Pilotos"}).click()
 await sidebar(page).getByRole("button",{name:"Inicio"}).click()
 await expect(page.getByRole("heading",{name:"Inicio · Lapex"})).toBeVisible()
 await expect(page.locator(".sidebar07-breadcrumb-bar").getByRole("button",{name:"Volver"})).toHaveCount(0)
})

test("Imágenes: avatares siempre acotados, variante original de vehículo",async({page})=>{
 await page.goto("/")
 await sidebar(page).getByRole("button",{name:"Recursos",exact:true}).click()
 await sidebar(page).getByRole("button",{name:"Vehículos"}).click()
 await page.locator(".page-tools").getByRole("button",{name:/Nuevo/}).click()
 const avatar=page.locator(".avatar-picker img.resource-avatar")
 await expect(avatar).toHaveAttribute("src",/vehicles\/vehicle-default-2\.png$/)
 await expect.poll(()=>avatar.evaluate(el=>(el as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
 const box=await avatar.boundingBox()
 expect(box&&box.width).toBeTruthy()
 expect(box!.width).toBeLessThanOrEqual(100)
 expect(box!.height).toBeLessThanOrEqual(100)
 for(const name of ["Elegir ilustración","Subir imagen","Restablecer predeterminada"])await expect(page.getByRole("button",{name,exact:true})).toBeVisible()
 await page.getByRole("button",{name:"Elegir ilustración"}).click()
 await expect(page.getByRole("dialog").getByRole("button",{name:"Elegir Silueta neutra de automóvil"})).toBeVisible()
})

